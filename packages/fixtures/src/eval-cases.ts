/**
 * Labelled evaluation set. ENTIRELY SYNTHETIC.
 *
 * Every request string below was written for this proof of concept. None is a
 * transcript, none is derived from a real call, and none contains PHI.
 *
 * IMPORTANT (P2.2): the split below is not cosmetic. `dev` cases may be used
 * while tuning weights and thresholds. `frozen` cases must not be inspected
 * while tuning; they exist to detect the overfitting that tuning produces.
 * `npm run eval -- --gate` reports both and gates on `frozen`.
 */

export type CaseSplit = 'dev' | 'frozen';

export interface EvalCase {
  id: string;
  tenantId: string;
  text: string;
  /** The single correct output state. */
  expectState: ResolutionState;
  /** For `resolved`, the visit type that must rank first. */
  expectVisitTypeId?: string;
  /** For `needs_information`, fields that must be asked about. */
  expectMissingFields?: string[];
  /** For `ambiguous`, ids that must all appear among the returned candidates. */
  expectCandidateIds?: string[];
  /**
   * A case is safety-critical when an incorrect `resolved` output would bypass a
   * configured safety rule. Any such bypass fails the build.
   */
  safetyCritical: boolean;
  tags: string[];
  split: CaseSplit;
}

